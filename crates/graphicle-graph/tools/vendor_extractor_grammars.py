def fetch(url, sha, cache):
    # Archives are cached under their basename; license files share one, so
    # they are cached under their pinned digest instead.
    names = [sha, url.rsplit("/", 1)[1]] if sha else [url.rsplit("/", 1)[1]]
    local = next((cache / n for n in names if cache and (cache / n).is_file()), None)
    data = local.read_bytes() if local else urllib.request.urlopen(url, timeout=120).read()
    digest = hashlib.sha256(data).hexdigest()
    if sha is not None and digest != sha:
        raise SystemExit(f"{url}: sha256 {digest} != pinned {sha}")
    return data, digest


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cache", type=Path)
    args = parser.parse_args()
    archives, written = {}, {}
    for name, spec in GRAMMARS.items():
        if spec["url"] not in archives:
            archives[spec["url"]] = tarfile.open(fileobj=io.BytesIO(fetch(spec["url"], spec["sha256"], args.cache)[0]))
        archive = archives[spec["url"]]
        crate = ROOT / "vendor" / name
        files = {}
        blobs = {f: archive.extractfile(spec["prefix"] + f).read() for f in spec["files"]}
        if "headers_from" in spec:
            blobs.update(written[spec["headers_from"]])
        for relative, blob in blobs.items():
            target = relative.replace("src/", "grammar/", 1)
            (crate / target).parent.mkdir(parents=True, exist_ok=True)
            (crate / target).write_bytes(blob)
            files[target] = hashlib.sha256(blob).hexdigest()
        written[name] = {f: b for f, b in blobs.items() if f.startswith("src/tree_sitter/")}
        license_source, license_sha = spec["license"]
        if license_source.startswith("https://"):
            license_blob, _ = fetch(license_source, license_sha, args.cache)
        else:
            license_blob = archive.extractfile(license_source).read()
        (crate / "LICENSE").write_bytes(license_blob)
        files["LICENSE"] = hashlib.sha256(license_blob).hexdigest()
        receipt = {"url": spec["url"], "sha256": spec["sha256"], "files": files, "note": spec["note"]}
        if "grammar" in spec:
            receipt["grammar"] = spec["grammar"]
        if license_source.startswith("https://"):
            receipt["license_url"] = license_source
        (crate / "SOURCE.json").write_text(json.dumps(receipt, indent=2) + "\n")
        print(name, len(files), "files")


if __name__ == "__main__":
    main()
