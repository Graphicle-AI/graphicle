#!/usr/bin/env python3
"""Pin Unicode decimal parsing used by Python's int() configuration values."""
import unicodedata
from pathlib import Path
assert unicodedata.unidata_version == "15.0.0"
ranges=[]
previous=None
for cp in range(0x110000):
    try: value=unicodedata.decimal(chr(cp))
    except ValueError: continue
    if ranges and cp==ranges[-1][1]+1 and value==(previous+1)%10:
        ranges[-1][1]=cp
    else:
        assert value==0
        ranges.append([cp,cp])
    previous=value
text="// Unicode 15.0 decimal digit intervals, generated by tools/generate_decimal.py.\n"
text+="pub const DECIMAL: &[(u32,u32)] = &[\n"
text+="".join(f"    (0x{lo:x},0x{hi:x}),\n" for lo,hi in ranges)+"];\n"
(Path(__file__).resolve().parents[1] / "src/decimal_data.rs").write_text(text)
